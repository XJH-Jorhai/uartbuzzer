@dataclass(frozen=True)
class BeamSettings:
    width:int=2
    horizon:int=4
    commit:int=4
    candidates:int=16
    terminal:str='baseline_rollout_terminal'
    terminal_ms:float=1.
    terminal_weight:float=1.
    chunk_frames:int=1024
    budget_ratio:float=5.
    objective:str='track_current'

def settings_for(mode,overrides=None):
    if mode not in BEAM_MODES:raise ValueError('未知Beam模式')
    settings=asdict(BeamSettings())
    if mode=='beam_quality':settings.update(width=4,horizon=8,candidates=64,terminal_ms=4.,budget_ratio=30.)
    if mode=='beam_research':settings.update(width=8,horizon=8,candidates=256,terminal='archived_rollout',terminal_ms=0.,budget_ratio=30.)
    extra=dict(overrides or {});unknown=set(extra)-set(settings)
    if unknown:raise ValueError('未知Beam参数: '+','.join(sorted(unknown)))
    settings.update(extra);s=BeamSettings(**settings)
    if s.width not in (2,4,8,16) or s.horizon not in (4,8,12) or s.commit not in (1,2,4,8) or s.commit>s.horizon:raise ValueError('Beam宽度/前瞻/提交参数无效')
    if s.candidates not in (16,32,64,128,256):raise ValueError('Beam候选数无效')
    if s.terminal not in ('no_terminal','baseline_rollout_terminal','state-aware_terminal','archived_rollout'):raise ValueError('未知Beam末端处理')
    if s.terminal_ms not in (0,1,2,4,8) or s.objective!='track_current':raise ValueError('应用Beam只提供已验证的电流跟踪目标')
    if not np.isfinite(s.terminal_weight) or not 0<=s.terminal_weight<=4:raise ValueError('Beam末端权重无效')
    if s.chunk_frames not in (256,512,1024,2048,4096):raise ValueError('Beam分块大小无效')
    if not np.isfinite(s.budget_ratio) or not 0<s.budget_ratio<=300:raise ValueError('Beam预算需要0到300倍时长')
    return s

@dataclass
class EncodedUART:
    baud:int
    segments:list
    expected_duration:float
    model_hash:str
    prep_hash:str
    encoder_version:str
    diagnostics:dict

    @property
    def data(self):return b''.join(s['data'] for s in self.segments)

_GRAM_CACHE={}
def _gram_table(model,window):
    key=(model.model_hash,model.baud,window)
    if key in _GRAM_CACHE:return _GRAM_CACHE[key]
    table=np.zeros((window+1,6,6));q=model.H.T@model.H
    for k in range(window):table[k+1]=q+model.F.T@table[k]@model.F
    gPg=np.einsum('ai,kij,aj->ka',model.g,table,model.g,optimize=True)
    table.setflags(write=False);gPg.setflags(write=False)
    if len(_GRAM_CACHE)>24:_GRAM_CACHE.clear()
    _GRAM_CACHE[key]=(table,gPg)
    return table,gPg

def search_block(target,baseline,model,settings,initial=None,baseline_initial=None,reference_states=None,core_frames=None):
    """Low-level fixed-target API, also used by preregistered numerical benchmarks."""
    target=np.ascontiguousarray(target,float).reshape(-1,10);base=np.frombuffer(bytes(baseline),np.uint8).copy()
    if len(base)!=len(target) or not np.all(np.isfinite(target)):raise ValueError('Beam目标和完整帧字节长度不一致')
    initial=np.zeros(6) if initial is None else np.asarray(initial,float)
    baseline_initial=initial if baseline_initial is None else np.asarray(baseline_initial,float)
    by,bs=trajectory(base,model.F,model.g,model.H,model.q,baseline_initial)
    return _search_prepared(target,base,model,settings,initial,by,bs,reference_states,core_frames)


def _model_terms(model):
    # A document-local cache: no model hash collision, cross-call state or borrowed
    # writable arrays. Immutable byte owners also prevent setflags(write=True).
    def immutable(value):
        a=np.ascontiguousarray(value)
        return np.frombuffer(a.tobytes(),dtype=a.dtype).reshape(a.shape)
    return (immutable(np.sum(model.q**2,axis=1)),
            immutable(model.q@model.H),immutable(model.H.T@model.H))


def _search_prepared(target,base,model,settings,initial,by,bs,reference_states,core_frames,terms=None):
    # Only the caller which generated by/bs for this exact base and initial state
    # may reuse them. Public search_block still computes its own trajectory.
    rs=bs if reference_states is None else np.ascontiguousarray(reference_states,float)
    if rs.shape!=(len(base)+1,6):raise ValueError('参考状态长度不匹配')
    window=2 if settings.terminal=='archived_rollout' else round(settings.terminal_ms*model.baud/10000)
    table,action_gram=_gram_table(model,window);indices=np.minimum(window,np.arange(len(base),-1,-1))
    gram=np.ascontiguousarray(table[indices])
    r=terminal_linear(by-target,model.F,model.H,max(window,1)) if settings.terminal in ('baseline_rollout_terminal','archived_rollout') else np.zeros((len(base)+1,6))
    terminal={'no_terminal':0,'baseline_rollout_terminal':1,'state-aware_terminal':2,'archived_rollout':1}[settings.terminal]
    qenergy,Hq,Q=_model_terms(model) if terms is None else terms
    action_cost=np.ascontiguousarray(qenergy[None,:]+np.sum(target**2,axis=1)[:,None]-2*np.einsum('nt,at->na',target,model.q))
    projection=np.ascontiguousarray(target@model.H);gPg=np.ascontiguousarray(action_gram[indices])
    core=len(base) if core_frames is None else int(core_frames)
    encoded,state,expanded=beam_chunk(target,base,bs,rs,model.F,model.g,model.H,model.q,gram,r,initial,
        settings.width,settings.horizon,settings.commit,settings.candidates,terminal,.75 if settings.terminal=='archived_rollout' else settings.terminal_weight,core,
        action_cost,Hq,Q,projection,gPg)
    return encoded.tobytes(),state,int(expanded)

def command_block(pcm,rate,baud,start_frame,frames,bias,amplitude,begin,end,soft_edges,source_time=None):
    t=(np.arange(start_frame*10,(start_frame+frames)*10)+.5)/baud
    command=bias+amplitude*np.interp(t,np.arange(len(pcm))/rate if source_time is None else source_time,pcm)
    if soft_edges:
        edge=np.minimum(np.clip((t-begin*10/baud)/.016,0,1),np.clip((end*10/baud-t)/.016,0,1))
        command=.1+(command-.1)*edge
    return np.ascontiguousarray(command)

def encode_segments(pcm,baseline_segments,profile,fit_path,rate=16000,progress=None,cancel_check=None,initial_state=None,command_factory=None,prep_hash=None):
    """Bounded-memory, overlapping lookahead with real state carry and global fallback.
    The caller generates the ACTUAL application baseline with the same processed PCM.
    """
    mode=profile['encoder'];settings=settings_for(mode,profile.get('beam_settings'))
    model=load_model(fit_path,profile['baud']);baud=model.baud
    initial=np.zeros(6) if initial_state is None else np.asarray(initial_state,float)
    if initial.shape!=(6,) or not np.all(np.isfinite(initial)):raise ValueError('无效Beam初始状态')
    pcm=np.asarray(pcm,float);frames_total=int(len(pcm)/rate*baud/10)
    source_time=np.arange(len(pcm))/rate
    if not np.all(np.isfinite(pcm)):raise ValueError('非有限音频')
    prep=prep_hash or hashlib.sha256(np.ascontiguousarray(pcm,dtype=np.float64).tobytes()).hexdigest()
    tic=time.perf_counter();deadline=tic+settings.budget_ratio*len(pcm)/rate
    backend_before=backend_info()
    baseline_cost=0.;candidate_cost=0.;xb=initial.copy();xc=initial.copy();xr=initial.copy();cursor=0
    candidates=[];expansions=0;optimized=0;budget_hit=False;seams=[]
    look=max(settings.horizon+2,round(settings.terminal_ms*baud/10000)+settings.horizon)
    terms=_model_terms(model)
    def cancelled():
        if cancel_check and cancel_check():raise InterruptedError('Beam编码已取消')
    def gap(end):
        nonlocal xb,xc,xr,cursor,baseline_cost,candidate_cost
        count=end-cursor
        if count<=0:return
        gram=finite_gram(model.F,model.H,count)
        db=xb-xr;dc=xc-xr;baseline_cost+=float(db@gram@db);candidate_cost+=float(dc@gram@dc)
        fade=np.linalg.matrix_power(model.F,count);xb=fade@xb;xc=fade@xc;xr=fade@xr;cursor=end
    for seg in baseline_segments:
        cancelled();begin=round(seg['start_s']*baud/10);end=begin+len(seg['data']);gap(begin)
        base=seg['data'];parts=[]
        for local in range(0,len(base),settings.chunk_frames):
            cancelled();core=min(settings.chunk_frames,len(base)-local);span=min(core+look,len(base)-local)
            command=command_factory(begin+local,span) if command_factory is not None else command_block(pcm,rate,baud,begin+local,span,profile['bias'],profile['amplitude'],begin,end,profile.get('soft_carrier_edges',False),source_time)
            target,refs=reference(command,model.bit_F,model.bit_g,model.half_F,model.half_g,xr)
            baseline=base[local:local+span];by,bs=trajectory(np.frombuffer(baseline,np.uint8),model.F,model.g,model.H,model.q,xb)
            budget_hit=budget_hit or time.perf_counter()>deadline
            if not budget_hit:
                data,_,count=_search_prepared(target,np.frombuffer(baseline,np.uint8).copy(),model,settings,xc,by,bs,refs,core,terms)
                expansions+=count;optimized+=core
            else:data=baseline[:core]
            cy,cs=trajectory(np.frombuffer(data,np.uint8),model.F,model.g,model.H,model.q,xc)
            baseline_cost+=float(np.sum((by[:core]-target[:core])**2));candidate_cost+=float(np.sum((cy-target[:core])**2))
            seams.append(dict(frame=begin+local,first_frame_error=float(np.mean((cy[0]-target[0])**2)),
                              last_frame_error=float(np.mean((cy[-1]-target[core-1])**2))))
            xb=bs[core].copy();xc=cs[-1].copy();xr=refs[core].copy();cursor=begin+local+core
            parts.append(data)
            if progress:progress(cursor/max(frames_total,1))
            cancelled()
        candidates.append(dict(start_s=seg['start_s'],end_s=seg['end_s'],data=b''.join(parts)))
    gap(frames_total);cancelled()
    # Whole-file incumbent, including OFF gaps; no local-switch monotonicity claim.
    use_baseline=budget_hit or candidate_cost>baseline_cost+1e-12
    segments=[dict(s) for s in (baseline_segments if use_baseline else candidates)]
    backend=backend_info()
    backend['scratch_calls']-=backend_before['scratch_calls'];backend['original_calls']-=backend_before['original_calls']
    meta=dict(encoder=mode,encoder_version=ENCODER_VERSION,model_version=MODEL_VERSION,model_hash=model.model_hash,
        kernel_backend=backend,
        model_label='measured M2 electrical current model',prep_hash=prep,parameters=asdict(settings),
        compiled=COMPILED,seconds=time.perf_counter()-tic,budget_ratio=settings.budget_ratio,budget_hit=budget_hit,
        baseline_encoder=profile.get('beam_baseline_encoder','bit_feedback_uart_v1'),baseline_SSE=baseline_cost,
        raw_candidate_SSE=candidate_cost,returned_SSE=baseline_cost if use_baseline else candidate_cost,
        fallback=use_baseline,fallback_reason='budget' if budget_hit else 'whole_document_objective' if use_baseline else None,
        optimized_frames=optimized,total_frames=frames_total,expanded_candidates=expansions,
        primary_objective='sum squared normalized M2 bit-center current error; includes actual OFF gaps',
        initial_state=initial.tolist(),state_carry=True,chunk_seam_errors=seams,global_optimality='heuristic',
        format='8N1',volume=float(profile.get('beam_volume',1.)),fixed_volume=True,
        expected_wire_s=sum(len(s['data'])*10/baud for s in segments),
        sound_quality_claim='No acoustic or THD superiority guarantee')
    if progress:progress(1.)
    return EncodedUART(baud,segments,meta['expected_wire_s'],model.model_hash,prep,ENCODER_VERSION,meta)
