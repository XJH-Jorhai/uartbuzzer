import argparse
import itertools
import platform
import sys
import time
from datetime import datetime
from pathlib import Path
import numpy as np
import scipy
import matplotlib
from .io_data import discover,observations,read_csv,dump,write_csv,inspect_dlog
from .impedance import fit,network,NAMES
from .spice import Engine,ac_check,simulate,DEFAULT
from .metrics import electrical,spectrum,edge_metrics
from .uart_codec import encode,tone_target,events,signal_suite
from .plots import impedance_plots,wave_plot,pareto_plot
from .optimize import sensitivity_configs,nondominated

ROOT=Path(__file__).resolve().parents[2]
METHODS=['naive_byte_density','frame_aware_pdm','frame_aware_sigma_delta']


def main():
    parser=argparse.ArgumentParser(description='Offline reproducible UART buzzer study; never energizes hardware')
    parser.add_argument('--dll');parser.add_argument('--out',type=Path)
    parser.add_argument('--stage',choices=['A','B','C','D','all'],default='all')
    parser.add_argument('--quick',action='store_true',help='smoke subset, explicitly not the complete study')
    args=parser.parse_args()
    out=args.out or ROOT/'results/study'/datetime.now().strftime('%Y%m%d_%H%M%S')
    # Existing runs must not be accidentally replaced.
    out.mkdir(parents=True,exist_ok=False)
    for folder in ('fit','spice','plots','uart','tables'):(out/folder).mkdir()
    dump(out/'environment.json',dict(python=sys.version,platform=platform.platform(),numpy=np.__version__,
         scipy=scipy.__version__,matplotlib=matplotlib.__version__,arguments=vars(args),seed=20261028,
         hardware_send_enabled=False))
    chosen,dlogs=discover(ROOT,out);inspect_dlog(dlogs,out)
    groups={k:observations(chosen[k]) for k in ('wide','fine')}
    dcr=np.array([float(r['DCR_ohm']) for r in read_csv(chosen['dcr'])])
    dump(out/'data_quality.json',dict(dcr_mean=dcr.mean(),dcr_sd=dcr.std(ddof=1),
         measurements={k:{n:v for n,v in g.items() if n not in ('raw_rows','f','z')} for k,g in groups.items()},
         low_level=read_csv(chosen['low']) if 'low' in chosen else [],
         note='VAC/IAC monitors are suspected swapped/derived, excluded from calibration and fitting'))
    print('Stage A: robust passive impedance fit',flush=True)
    p,model,fitted=fit(groups,dcr,out/'fit',starts=3 if args.quick else 8,bootstraps=4 if args.quick else 32)
    impedance_plots(groups,p,model,out/'plots')
    (out/'spice/fitted_load.lib').write_text('* Fitted passive network; generated by run.py\n.subckt FITTED load sh\n'+'\n'.join(network(p,model))+'\n.ends FITTED\n',encoding='ascii')
    engine=Engine(args.dll);ac=ac_check(engine,p,model,out/'spice')
    print('Fit selected',model,'AC check',ac,flush=True)
    checkpoints=dict(A='completed',B='pending',C='pending',D='pending')
    dump(out/'checkpoints.json',checkpoints)
    rows=[];spectra=[];edges=[];runtime=[];scan=[];mc=[]
    def run_case(name,wave,dur,cfg,start=.006,end=None,dt=2e-7,f=None,edge_baud=None,save=True):
        c=DEFAULT|cfg
        a=simulate(engine,p,model,wave,dur,out/'spice'/(name+'.cir'),c,dt,save)
        row=dict(case=name,**c,**electrical(a,p,c,start,end))
        if f:
            sm,fft=spectrum(a,f,start,end or dur);row.update(sm)
        if edge_baud:
            em=edge_metrics(a,edge_baud,c['vio']);row.update(em);edges.append(dict(case=name,**em))
        rows.append(row)
        return a,row
    if args.stage=='A':
        finish(out,p,model,fitted,ac,rows,checkpoints);return
    print('Stage B: transistor / diode SPICE benchmarks, static and fault cases',flush=True)
    for top in ('pnp','pmos','dual_nmos','single_nmos'):
        a,r=run_case(top+'_2k', 'PULSE(5 0 500u 10n 10n 250u 500u)',.024,dict(topology=top),start=.018,end=.024,f=2000)
        wave_plot(a,out/'plots'/(top+'_2k.png'),top+' 2 kHz 50%: provisional devices',(.008,.0095))
        for mode,vio,txmode,wave,supplymode in [
            ('idle5',5,'normal','DC 5','normal'),('idle33',3.3,'normal','DC 3.3','normal'),
            ('stuck_low',5,'normal','DC 0','normal'),('highZ',5,'highZ','DC 0','normal'),
            ('usb_dead',0,'unpowered','DC 0','normal'),('power_loss',5,'power_loss','DC 5','normal'),
            ('common_power_cycle',5,'highZ','DC 0','cycle')]:
            a,r=run_case(top+'_'+mode,wave,.006,dict(topology=top,vio=vio,tx_mode=txmode,supply_mode=supplymode),start=.004)
            if mode in ('usb_dead','power_loss'):wave_plot(a,out/'plots'/(top+'_'+mode+'.png'),top+' '+mode)
        for vio in (3.3,5.):
            for baud in (460800,921600):
                # Alternate all-zero / all-one creates both 1-bit and 9-bit intervals.
                w,dur=events(bytes([0,255,85,170])*30,baud,vio)
                a,r=run_case(f'{top}_bits_{vio}_{baud}',w,dur,dict(topology=top,vio=vio),
                            start=.0007,end=dur-.0005,dt=5e-8,edge_baud=baud)
                if vio==5 and baud==921600:wave_plot(a,out/'plots'/(top+'_bits.png'),top+' 921600 baud',(.0005,.00055))
        for val in (0,255):
            w,dur=events(bytes([val])*300,460800)
            run_case(f'{top}_constant_{val}',w,dur,dict(topology=top),start=.003,end=dur-.0005,dt=1e-7)
        run_case(top+'_open','PULSE(5 0 500u 10n 10n 250u 500u)',.004,dict(topology=top,open_load=True),start=.002)
    checkpoints['B']='completed';dump(out/'checkpoints.json',checkpoints)
    write_csv(out/'tables/benchmark.csv',rows)
    if args.stage=='B':
        finish(out,p,model,fitted,ac,rows,checkpoints);return
    print('Stage C: actual 8N1 byte encoders through both high-side switches',flush=True)
    frequencies=[2000] if args.quick else [440,880,1760,2000,2150,2400,3520]
    for baud,method,f in itertools.product([230400,460800,921600],METHODS,frequencies):
        target=tone_target(f,baud,.032)
        b,state,cost=encode(target,method);runtime.append(dict(baud=baud,method=method,f_Hz=f,final_integral_error=state,**cost))
        name=f'{method}_{baud}_{f}'
        (out/'uart'/(name+'.bin')).write_bytes(b)
        w,dur=events(b,baud)
        # Twelve ms or more steady data, minimum >5 cycles at 440 Hz.
        for top in ('pnp','pmos'):
            a,r=run_case(top+'_'+name,w,dur,dict(topology=top,rg=220),start=.016,end=dur-.0005,dt=1/baud/12,f=f,edge_baud=baud,save=(f==2000))
            spectra.append(r | dict(baud=baud,method=method,f_Hz=f))
            if f==2000 and baud==921600:
                sm,(ff,amp)=spectrum(a,f,.016,dur-.0005)
                write_csv(out/'tables'/(top+'_'+method+'_spectrum.csv'),[dict(f_Hz=x,current_peak_A=y) for x,y in zip(ff,amp)])
    b,schedule=signal_suite(921600)
    (out/'uart/notes_rests_sweep.bin').write_bytes(b);dump(out/'uart/notes_rests_sweep_schedule.json',schedule)
    gaps={r['frame_index']:r['duration_s'] for r in schedule if r['kind']=='idle_gap'}
    # Explicit simulated USB jitter gap, independent of the musical rest.
    gaps[37]=.0003
    w,dur=events(b,921600,gaps=gaps)
    for top in ('pnp','pmos'):
        a,r=run_case(top+'_notes_gaps',w,dur,dict(topology=top,rg=220),start=.004,dt=8e-8)
        wave_plot(a,out/'plots'/(top+'_notes_gaps.png'),top+' byte-stream melody, rest, sweep and USB gap')
    write_csv(out/'tables/encoder_cost.csv',runtime);write_csv(out/'tables/uart_comparison.csv',spectra)
    checkpoints['C']='completed';dump(out/'checkpoints.json',checkpoints)
    if args.stage=='C':
        finish(out,p,model,fitted,ac,rows,checkpoints);return
    print('Stage D: resistor, edge, clamp, bias/amplitude and uncertainty scans',flush=True)
    w,dur=events(bytes([0,255,85,170])*20,921600)
    for rg,rgs in itertools.product([0,47,100,220,470],[1000,4700,10000,22000]):
        a,r=run_case(f'gate_{rg}_{rgs}',w,dur,dict(topology='pmos',rg=rg,rgs=rgs),start=.0006,end=dur-.0005,dt=5e-8,edge_baud=921600,save=False)
        scan.append(r)
    for rb,rpull in itertools.product([330,470,680,1000,2200],[1000,2200,4700,10000]):
        a,r=run_case(f'base_{rb}_{rpull}',w,dur,dict(topology='pnp',rb=rb,rpull=rpull),start=.0006,end=dur-.0005,dt=5e-8,edge_baud=921600,save=False)
        scan.append(r)
    for q1,txp in itertools.product([470,1000,2200],[10000,22000,47000]):
        a,r=run_case(f'dual_{q1}_{txp}',w,dur,dict(topology='dual_nmos',q1pull=q1,txpull=txp,vio=3.3),start=.0006,end=dur-.0005,dt=5e-8,edge_baud=921600,save=False)
        scan.append(r)
    for top,rl,cl in itertools.product(['pnp','pmos','dual_nmos'],[0,10,22,33,47,68],[0,22]):
        a,r=run_case(f'limit_{top}_{rl}_{cl}','PULSE(5 0 500u 10n 10n 250u 500u)',.01,
                     dict(topology=top,rlimit=rl,clamp_r=cl,rg=220),start=.006,end=.01,f=2000,save=False)
        scan.append(r)
    for top in ('pnp','pmos'):
        for baud,bias,amp in itertools.product([460800,921600],[.3,.5],[.15,.2,.35]):
            target=tone_target(2000,baud,.014,bias,amp);b,_,_=encode(target,'frame_aware_sigma_delta');w,dur=events(b,baud)
            a,r=run_case(f'bias_{top}_{baud}_{bias}_{amp}',w,dur,dict(topology=top,rg=220,rlimit=33),start=.004,end=dur-.0005,dt=1/baud/12,f=2000,save=False)
            r.update(baud=baud,bias=bias,amplitude=amp);scan.append(r)
    a,r=run_case('pnp_schottky',w,dur,dict(topology='pnp',schottky=True),start=.004,end=dur-.0005,dt=5e-8,edge_baud=921600,save=False)
    scan.append(r)
    for j,cfg in enumerate(sensitivity_configs(n=3 if args.quick else 24)):
        # Mix 2 kHz heating and worst-edge UART sensitivity, separately labelled.
        stim='PULSE(5 0 500u 10n 10n 250u 500u)' if j%2==0 else w
        duration=.008 if j%2==0 else dur
        a,r=run_case(f'mc_{j:03d}',stim,duration,cfg,start=.004,end=(.008 if j%2==0 else dur-.0005),dt=1e-7,save=False)
        r['stimulus']='2k_square' if j%2==0 else 'uart_2k';mc.append(r)
    # Deterministic DC fault corners, not reliant on random coverage.
    for top,rcu,supply,rl in itertools.product(['pnp','pmos','dual_nmos'],[37,40.80377,47],[4.75,5.25],[0,33,68]):
        a,r=run_case(f'dc_{top}_{rcu}_{supply}_{rl}','DC 0',.004,dict(topology=top,rcu=rcu,supply=supply,rlimit=rl),start=.003,save=False)
        mc.append(r)
    write_csv(out/'tables/component_scan.csv',scan);write_csv(out/'tables/sensitivity.csv',mc)
    for top in ('pnp','pmos'):
        worst=max((r for r in mc if r['topology']==top),key=lambda r:r['Ipeak_A'])
        cfg={k:worst[k] for k in DEFAULT}
        stim='DC 0' if worst['case'].startswith('dc_') else ('PULSE(5 0 500u 10n 10n 250u 500u)' if worst['stimulus']=='2k_square' else w)
        duration=.008 if isinstance(stim,str) else dur
        a,r=run_case(top+'_sampled_worst',stim,duration,cfg,start=.004,dt=5e-8)
        wave_plot(a,out/'plots'/(top+'_sampled_worst.png'),top+' sampled worst current corner')
    front=nondominated(scan+spectra);write_csv(out/'tables/pareto.csv',front);pareto_plot(scan+spectra,out/'plots')
    dump(out/'tables/monte_carlo_summary.json',{
        top:{key:max(r[key] for r in mc if r['topology']==top) for key in
             ['Ipeak_A','Irms_A','Pcu_W','TX_sink_peak_A','TX_source_peak_A','Vcontrol_abs_peak_V','Vswitch_abs_peak_V']}
        for top in ('pnp','pmos','dual_nmos')})
    checkpoints['D']='completed';dump(out/'checkpoints.json',checkpoints)
    finish(out,p,model,fitted,ac,rows,checkpoints)


def finish(out,p,model,fitted,ac,rows,checkpoints):
    write_csv(out/'tables/all_cases.csv',rows)
    dump(out/'summary.json',dict(selected_model=model,spice_AC=ac,checkpoints=checkpoints,cases=len(rows),
         max_shunt_error_A=max((r['shunt_error_A'] for r in rows),default=0),
         max_energy_relative_error=max((r['energy_relative_error'] for r in rows if not r.get('open_load')),default=0)))
    (ROOT/'results/latest_study.txt').write_text(str(out.resolve()),encoding='utf-8')
    from .report import make_report
    make_report(ROOT,out,p,model,fitted,ac,rows,checkpoints)
    print('Outputs:',out,flush=True)
